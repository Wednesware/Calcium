def inventory():
    """Describe every public builtin of the compiler's Python, without invoking it."""
    import builtins

    names = {name for name in vars(builtins) if not name.startswith("_")} | {
        "__debug__",
        "__import__",
    }
    return {
        "python_version": __import__("sys").version.split()[0],
        "meaning": "Native availability covers the documented overloads, not complete CPython reflection or all special protocols",
        "builtins": {
            name: {
                "status": "native" if name in SUPPORTED else "unsupported",
                "scope": "See docs/BUILTINS.md"
                if name in SUPPORTED
                else UNSUPPORTED.get(name, "Native implementation unavailable"),
            }
            for name in sorted(names)
        },
    }
