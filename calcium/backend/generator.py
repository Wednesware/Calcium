"""Deterministic C11 generation from validated CIR, with explicit owned locals."""

import json
import math

from .. import __version__
from ..ir.nodes import Function, Program
from ..ir.validator import validate


def cstr(text: str | bytes) -> str:
    raw = text if isinstance(text, bytes) else text.encode("utf-8", "surrogatepass")
    return '"' + "".join(f"\\{byte:03o}" for byte in raw) + '"'


def generate(
    program: Program,
    *,
    filename: str,
    directory: str,
    module_name: str,
    python_executable: str,
    executor: str | None = None,
) -> str:
    validate(program)
    constants = {}

    def collect(data):
        key = json.dumps(data, sort_keys=True)
        if key not in constants:
            if data["type"] == "tuple":
                for value in data["value"]:
                    collect(value)
            constants[key] = (len(constants) + 1, data)
        return constants[key][0]

    for fn in program.functions:
        for block in fn.blocks:
            for op in block.instructions:
                if op.op == "constant":
                    collect(op.data)
    code = [
        f"/* Generated by Calcium {__version__}. All Python-object results are owned. */",
        '#include "program.h"',
        "#include <math.h>",
        "#if PY_MAJOR_VERSION != 3 || PY_MINOR_VERSION != CALCIUM_PY_MINOR",
        '#error "Calcium target Python header version mismatch"',
        "#endif",
    ]
    if program.mode == "fallback":
        code += [
            f"static int ca_execute(PyObject *g) {{ return ca_execute_source({cstr(program.fallback_source)}, {cstr(filename)}, g); }}"
        ]
    else:
        for fn in program.functions:
            code.append(
                f"static PyObject *{fn.symbol}(PyObject *g, PyObject *args, PyObject *kwargs);"
            )
        for fn in program.functions:
            if not fn.module:
                code.append(
                    f"static PyMethodDef {fn.symbol}_def = {{{cstr(fn.name)}, (PyCFunction)(void(*)(void)){fn.symbol}, METH_VARARGS | METH_KEYWORDS, {'NULL' if fn.doc is None else cstr(fn.doc)}}};"
                )
        for fn in program.functions:
            code.extend(emit_function(fn, constants, filename=filename))
        code += [
            "static int ca_execute(PyObject *g) {",
            f"    PyObject *context = PyTuple_New({len(constants) + 1});",
            "    PyObject *value = NULL, *result = NULL, *error = NULL;",
            "    if (!context) return -1;",
            "    PyTuple_SET_ITEM(context, 0, Py_NewRef(g));",
        ]
        for index, data in constants.values():
            expr = constant_expression(data, constants)
            code += [
                f"    value = {expr};",
                "    if (!value) goto failed;",
                f"    PyTuple_SET_ITEM(context, {index}, value);",
            ]
        code += [
            "    result = ca_module(context, NULL, NULL);",
            "    if (!result) goto failed;",
            "    Py_DECREF(result); Py_DECREF(context); return 0;",
            "failed:",
            "    error = PyErr_GetRaisedException();",
            "    Py_DECREF(context); PyErr_SetRaisedException(error); return -1;",
            "}",
        ]
    if executor is not None:
        return "\n".join(code).replace("static int ca_execute(", f"int {executor}(") + "\n"
    code += [
        "#ifndef CALCIUM_EXTENSION",
        f"int main(int argc, char **argv) {{ return ca_main(argc, argv, {cstr(filename)}, {cstr(directory)}, {cstr(python_executable)}, ca_execute); }}",
        "#else",
        "static int ca_exec_extension(PyObject *module) {",
        "    PyObject *g = PyModule_GetDict(module);",
        '    if (PyDict_SetItemString(g, "__builtins__", PyEval_GetBuiltins()) < 0) return -1;',
        "    return ca_execute(g);",
        "}",
        "static PyModuleDef_Slot ca_slots[] = {{Py_mod_exec, ca_exec_extension}, {0, NULL}};",
        f"static struct PyModuleDef ca_def = {{PyModuleDef_HEAD_INIT, {cstr(module_name)}, NULL, 0, NULL, ca_slots, NULL, NULL, NULL}};",
        f"PyMODINIT_FUNC PyInit_{module_name}(void) {{ return PyModuleDef_Init(&ca_def); }}",
        "#endif",
        "",
    ]
    return "\n".join(code)


def emit_function(fn: Function, constants: dict, *, filename: str) -> list[str]:
    out = [f"static PyObject *{fn.symbol}(PyObject *context, PyObject *args, PyObject *kwargs) {{"]
    if not fn.module:
        out += [
            "    PyObject *defaults = PyTuple_GET_ITEM(context, 1);",
            "    PyObject *kwdefaults = PyTuple_GET_ITEM(context, 2);",
            "    context = PyTuple_GET_ITEM(context, 0);",
        ]
    out += [
        "    PyObject *g = PyTuple_GET_ITEM(context, 0);",
        "    PyObject *result = NULL, *saved_error = NULL;",
        "    int truth = 0;",
    ]
    out += [f"    PyObject *v{i} = NULL;" for i in range(fn.registers)]
    slots = {name: f"l{i}" for i, name in enumerate(fn.locals)}
    out += [f"    PyObject *{slot} = NULL;" for slot in slots.values()]
    if not fn.module:
        out.append(
            '    if (Py_EnterRecursiveCall(" while calling a Calcium function")) return NULL;'
        )
        out.append(
            "    static const char *keywords[] = {"
            + ", ".join(cstr(p) for p in fn.parameters)
            + (", " if fn.parameters else "")
            + "NULL};"
        )
        out.append(
            f"    PyObject *bound = ca_bind({cstr(fn.name)}, args, kwargs, {fn.posonly}, {fn.positional}, {len(fn.kwonly)}, {int(fn.vararg is not None)}, {int(fn.kwarg is not None)}, keywords, defaults, kwdefaults);"
        )
        out.append("    if (!bound) goto error;")
        for i, name in enumerate(fn.parameters):
            out.append(f"    {slots[name]} = Py_NewRef(PyTuple_GET_ITEM(bound, {i}));")
        out.append("    Py_DECREF(bound);")
    else:
        out.append("    (void)args; (void)kwargs;")
    out.append(f"    goto {fn.blocks[0].name};")
    for block in fn.blocks:
        out.append(f"{block.name}:;")
        for op in block.instructions:
            args = [f"v{i}" for i in op.args]
            target = f"v{op.result}"
            expr = None
            status = None
            out.append(f"    /* line {op.line}: {op.op} */")
            if op.op == "drop":
                out.append(f"    Py_CLEAR({args[0]});")
            elif op.op == "clear":
                out.append(f"    Py_CLEAR({slots[op.data]});")
            elif op.op == "load":
                if op.data in slots:
                    slot = slots[op.data]
                    out.append(
                        f"    if (!{slot}) {{ PyErr_Format(PyExc_UnboundLocalError, \"cannot access local variable '%s' where it is not associated with a value\", {cstr(op.data)}); goto error; }}"
                    )
                    expr = f"Py_NewRef({slot})"
                else:
                    expr = f"ca_lookup(g, {cstr(op.data)})"
            elif op.op == "store":
                if op.data in slots:
                    out.append(f"    Py_XSETREF({slots[op.data]}, Py_NewRef({args[0]}));")
                else:
                    status = f"PyDict_SetItemString(g, {cstr(op.data)}, {args[0]})"
            elif op.op == "delete":
                if op.data in slots:
                    slot = slots[op.data]
                    out.append(
                        f"    if (!{slot}) {{ PyErr_Format(PyExc_UnboundLocalError, \"cannot access local variable '%s' where it is not associated with a value\", {cstr(op.data)}); goto error; }}"
                    )
                    out.append(f"    Py_CLEAR({slot});")
                else:
                    status = f"ca_delete_global(g, {cstr(op.data)})"
            elif op.op == "python_definition":
                status = f"ca_execute_source({cstr(op.data)}, {cstr(filename)}, g)"
            elif op.op == "delattr":
                status = f"PyObject_DelAttrString({args[0]}, {cstr(op.data)})"
            elif op.op == "delitem":
                status = f"PyObject_DelItem({', '.join(args)})"
            elif op.op == "assert_fail":
                if args:
                    # Calling AssertionError preserves a tuple as one argument.
                    expr_args = f"(PyObject *[]){{{args[0]}}}"
                    out.append(
                        f"    result = ca_call(PyExc_AssertionError, 1, 0, {expr_args}, NULL);"
                    )
                    out.append("    if (!result) goto error;")
                    out.append(
                        "    PyErr_SetObject(PyExc_AssertionError, result); Py_CLEAR(result);"
                    )
                else:
                    out.append("    PyErr_SetNone(PyExc_AssertionError);")
            elif op.op == "raise":
                status = f"ca_raise({args[0] if args else 'NULL'}, {args[1] if len(args) > 1 else 'NULL'})"
            elif op.op == "args_append":
                status = f"PyList_Append({args[0]}, {args[1]})"
            elif op.op == "args_extend":
                status = f"ca_args_extend({args[0]}, {args[1]})"
            elif op.op == "dict_merge":
                status = f"PyDict_Update({args[0]}, {args[1]})"
            elif op.op == "to_tuple":
                expr = f"PyList_AsTuple({args[0]})"
            elif op.op == "unpack_ex":
                expr = f"ca_unpack_ex({args[0]}, {op.data['before']}, {op.data['after']})"
            elif op.op == "kwargs_set":
                status = f"ca_keyword_set({args[0]}, {cstr(op.data)}, {args[1]})"
            elif op.op == "kwargs_merge":
                status = f"ca_keywords_merge({args[0]}, {args[1]})"
            elif op.op == "call_ex":
                expr = f"ca_call_ex({', '.join(args)})"
            elif op.op == "convert_string":
                function = {115: "PyObject_Str", 114: "PyObject_Repr", 97: "PyObject_ASCII"}[
                    op.data
                ]
                expr = f"{function}({args[0]})"
            elif op.op == "format":
                expr = f"PyObject_Format({', '.join(args)})"
            elif op.op == "join_string":
                array = "(PyObject *[]){" + (", ".join(args) or "NULL") + "}"
                expr = f"ca_join_string({len(args)}, {array})"
            elif op.op == "unpack":
                expr = f"ca_unpack({args[0]}, {op.data})"
            elif op.op == "tuple_item":
                expr = f"Py_NewRef(PyTuple_GET_ITEM({args[0]}, {op.data}))"
            elif op.op == "constant":
                index = constants[json.dumps(op.data, sort_keys=True)][0]
                expr = f"Py_NewRef(PyTuple_GET_ITEM(context, {index}))"
            elif op.op == "checked_binary":
                expr = f"ca_checked_{op.data}({', '.join(args)})"
            elif op.op in {"binary", "inplace"}:
                name = "".join(part.title() for part in op.data.split("_"))
                name = ("InPlace" if op.op == "inplace" else "") + name
                expr = f"PyNumber_{name}({', '.join(args)}" + (
                    ", Py_None)" if op.data == "power" else ")"
                )
            elif op.op == "unary":
                name = {
                    "not": "ca_not",
                    "positive": "PyNumber_Positive",
                    "negative": "PyNumber_Negative",
                    "invert": "PyNumber_Invert",
                }[op.data]
                expr = f"{name}({args[0]})"
            elif op.op == "compare":
                if op.data in {"is", "is_not"}:
                    expr = (
                        f"PyBool_FromLong({args[0]} {'==' if op.data == 'is' else '!='} {args[1]})"
                    )
                elif op.data in {"in", "not_in"}:
                    expr = f"ca_contains({args[0]}, {args[1]}, {int(op.data == 'not_in')})"
                else:
                    expr = f"PyObject_RichCompare({args[0]}, {args[1]}, Py_{op.data.upper()})"
            elif op.op == "attribute":
                expr = f"PyObject_GetAttrString({args[0]}, {cstr(op.data)})"
            elif op.op == "getitem":
                expr = f"PyObject_GetItem({args[0]}, {args[1]})"
            elif op.op == "slice":
                expr = f"PySlice_New({', '.join(args)})"
            elif op.op in {"setattr", "setitem"}:
                status = (
                    f"PyObject_SetAttrString({args[0]}, {cstr(op.data)}, {args[1]})"
                    if op.op == "setattr"
                    else f"PyObject_SetItem({', '.join(args)})"
                )
            elif op.op == "import":
                names = (
                    "(const char *[]){"
                    + (", ".join(cstr(n) for n in op.data["fromlist"]) or "NULL")
                    + "}"
                )
                local_names = [name for name in fn.locals if not name.startswith("$")]
                local_keys = (
                    "(const char *[]){" + (", ".join(cstr(n) for n in local_names) or "NULL") + "}"
                )
                local_values = (
                    "(PyObject *[]){" + (", ".join(slots[n] for n in local_names) or "NULL") + "}"
                )
                count = -1 if fn.module else len(local_names)
                expr = f"ca_import_name(g, {cstr(op.data['name'])}, {op.data['level']}, {len(op.data['fromlist'])}, {names}, {count}, {local_keys}, {local_values})"
            elif op.op == "import_from":
                expr = f"ca_import_from({args[0]}, {cstr(op.data)})"
            elif op.op == "iter":
                expr = f"PyObject_GetIter({args[0]})"
            elif op.op == "function":
                array = "(PyObject *[]){" + (", ".join(args) or "NULL") + "}"
                keys = (
                    "(const char *[]){"
                    + (", ".join(cstr(n) for n in op.data["kwdefaults"]) or "NULL")
                    + "}"
                )
                expr = f'ca_make_function(&{op.data["symbol"]}_def, context, PyDict_GetItemString(g, "__name__"), {op.data["posdefaults"]}, {len(op.data["kwdefaults"])}, {array}, {keys})'
            elif op.op in {"call", "container"}:
                values = args[1:] if op.op == "call" else args
                array = "(PyObject *[]){" + (", ".join(values) or "NULL") + "}"
                if op.op == "container":
                    expr = f"ca_container({cstr(op.data)}, {len(values)}, {array})"
                else:
                    names = op.data["keywords"]
                    keywords = (
                        "(const char *[]){" + (", ".join(cstr(n) for n in names) or "NULL") + "}"
                    )
                    expr = f"ca_call({args[0]}, {op.data['positional']}, {len(names)}, {array}, {keywords})"
            else:
                raise AssertionError(op.op)
            if expr is not None:
                out += [f"    {target} = {expr};", f"    if (!{target}) goto error;"]
            if status is not None:
                out.append(f"    if ({status} < 0) goto error;")
        term = block.terminator
        value = f"v{term.args[0]}" if term.args else None
        if term.op == "return":
            out += [f"    result = {value}; {value} = NULL;", "    goto cleanup;"]
        elif term.op == "jump":
            out.append(f"    goto {term.targets[0]};")
        elif term.op == "branch":
            out += [
                f"    truth = PyObject_IsTrue({value});",
                "    if (truth < 0) goto error;",
                f"    Py_CLEAR({value});",
                f"    if (truth) goto {term.targets[0]}; else goto {term.targets[1]};",
            ]
        elif term.op == "next":
            item = f"v{term.result}"
            out += [
                f"    {item} = PyIter_Next({value});",
                f"    if (!{item} && PyErr_Occurred()) goto error;",
                f"    Py_CLEAR({value});",
                f"    if ({item}) goto {term.targets[0]}; else goto {term.targets[1]};",
            ]
        elif term.op == "error":
            out.append("    goto error;")
    out += ["error:", "    saved_error = PyErr_GetRaisedException();", "cleanup:;"]
    out += [f"    Py_CLEAR(v{i});" for i in reversed(range(fn.registers))]
    out += [f"    Py_CLEAR({slots[name]});" for name in fn.cleanup_order]
    if not fn.module:
        out.append("    Py_LeaveRecursiveCall();")
    out += [
        "    if (saved_error) PyErr_SetRaisedException(saved_error);",
        "    return result;",
        "}",
    ]
    return out


def constant_expression(data, constants):
    kind, value = data["type"], data["value"]
    if kind == "NoneType":
        return "Py_NewRef(Py_None)"
    if kind == "bool":
        return f"PyBool_FromLong({int(value)})"
    if kind == "int":
        return f"PyLong_FromString({cstr(value)}, NULL, 10)"
    if kind == "float":
        number = float(value)
        literal = (
            ("-Py_NAN" if math.copysign(1.0, number) < 0 else "Py_NAN")
            if math.isnan(number)
            else number.hex()
            if math.isfinite(number)
            else ("-Py_HUGE_VAL" if number < 0 else "Py_HUGE_VAL")
        )
        return f"PyFloat_FromDouble({literal})"
    if kind == "bytes":
        raw = bytes.fromhex(value)
        return f"PyBytes_FromStringAndSize({cstr(raw)}, {len(raw)})"
    if kind == "tuple":
        values = (
            ", ".join(
                f"PyTuple_GET_ITEM(context, {constants[json.dumps(v, sort_keys=True)][0]})"
                for v in value
            )
            or "NULL"
        )
        return f'ca_container("tuple", {len(value)}, (PyObject *[]){{{values}}})'
    intern = value.isascii() and all(c.isalnum() or c == "_" for c in value)
    return f"ca_unicode_constant({cstr(value)}, {len(value.encode('utf-8', 'surrogatepass'))}, {int(intern)})"
